# -*- coding: utf-8 -*-
"""Annotate the resolved markdown with the Word line numbers each block occupies.

Line numbers are a rendering property of Word (the docx stores only the
continuous-numbering rule, not the numbers), so the numbers come from Word
itself: the cumulative line count from the document start to the paragraph.

Output: manuscript_frontiers_v2.lines.md — same text, one `<!-- L n-m -->`
marker before each paragraph that maps, plus a coverage count so a missing
marker is visible rather than silently absent.
"""
from __future__ import annotations

import io
import re
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")

from pathlib import Path

from win32com.client import gencache

HERE = Path(__file__).resolve().parent
DOCX = HERE / "manuscript_frontiers_v2.docx"
MD = HERE / "manuscript_frontiers_v2.md"
OUT = HERE / "manuscript_frontiers_v2.lines.md"

WD_STAT_LINES = 1


def norm(s: str) -> str:
    s = re.sub(r"[*`]", "", s)
    s = re.sub(r"^#{1,6}\s+", "", s)        # heading marker
    s = re.sub(r"^\d+\.\s+", "", s)         # ordered-list marker (references)
    s = re.sub(r"^\\?\*?\s*", "", s)        # author asterisk
    s = re.sub(r"\s+", " ", s).strip()
    return s


ANCHORS = [
    "Administrative penalty decisions are among the most abundant",
    "Two rule systems run before any model sees",
    "Agreement between the channels is 0.7460",
    "Adjudicating the 270 sampled hits shows",
    "All three constructs failed the same gate",
]


def calibrate(spans: dict[str, tuple[int, int]]) -> int:
    """Line numbers are printed by Word, so measure them off the printed page.

    ComputeStatistics counts two lines the printed margin does not number
    (the template's empty first-page paragraphs), so the raw count runs high.
    Anchor a handful of paragraphs to the numbers the PDF actually prints,
    require every offset to agree, and return it. A non-uniform offset is a
    failure, not something to average over: it would mean the mapping drifts.
    """
    try:
        from pypdf import PdfReader
    except ImportError:
        from PyPDF2 import PdfReader
    text = "\n".join((pg.extract_text() or "")
                     for pg in PdfReader(str(HERE / "manuscript_frontiers_v2.pdf")).pages)
    offsets = []
    for a in ANCHORS:
        i = text.find(a)
        m = re.search(r"(\d+)\s*$", text[i:text.find("\n", i)]) if i >= 0 else None
        key = norm(a)
        hit = next((k for k in spans if k.startswith(key[:60])), None)
        span = spans.get(hit) if hit else None
        if not m or not span:
            print(f"  anchor not located: {a[:40]!r} printed={bool(m)} computed={bool(span)}")
            continue
        offsets.append(span[0] - int(m.group(1)))
        print(f"  anchor {a[:38]!r:42s} computed {span[0]:4d} printed {int(m.group(1)):4d} "
              f"offset {offsets[-1]:+d}")
    if len(offsets) < 4 or len(set(offsets)) != 1:
        raise SystemExit(f"line-number offset not uniform: {offsets}")
    return offsets[0]


def main() -> int:
    app = gencache.EnsureDispatch("Word.Application")
    app.Visible = False
    app.DisplayAlerts = 0
    doc = app.Documents.Open(str(DOCX), ReadOnly=True)

    spans: dict[str, tuple[int, int]] = {}
    for p in doc.Paragraphs:
        txt = norm(p.Range.Text.replace("\r", "").replace("\x07", ""))
        if not txt:
            continue
        start = doc.Range(0, p.Range.Start).ComputeStatistics(WD_STAT_LINES) + 1
        end = start + max(0, p.Range.ComputeStatistics(WD_STAT_LINES) - 1)
        spans.setdefault(txt[:80], (start, end))
    doc.Close(False)
    app.Quit()

    off = calibrate(spans)
    spans = {k: (s - off, e - off) for k, (s, e) in spans.items()}

    lines = MD.read_text(encoding="utf-8").split("\n")
    out, hits, misses = [], 0, 0
    for i, line in enumerate(lines):
        if line.strip() and not line.startswith("|"):
            key = norm(line)[:80]
            nxt = next((l for l in lines[i + 1:] if l.strip()), "")
            is_para = (i == 0 or not lines[i - 1].strip()) and not nxt.startswith("|---")
            if is_para:
                span = spans.get(key)
                if span:
                    out.append(f"<!-- L {span[0]}-{span[1]} -->")
                    hits += 1
                else:
                    misses += 1
        out.append(line)

    header = [
        "<!-- Generated by line_map_v2.py. Each marker gives the line numbers the",
        "     block occupies in manuscript_frontiers_v2.docx as printed in the left",
        "     margin (continuous numbering, calibrated against five anchors in the",
        "     exported PDF; the raw Word count runs +2 because the template's first",
        "     page contributes two unnumbered lines).",
        "     Front matter, the figure image line and table cells carry no marker:",
        "     the first five are page 1, the table rows are not paragraphs. -->",
        "",
    ]
    OUT.write_text("\n".join(header + out), encoding="utf-8")
    print(f"mapped {hits} blocks, {misses} unmatched -> {OUT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
